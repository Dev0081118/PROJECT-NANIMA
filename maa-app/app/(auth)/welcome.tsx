import React, { useState } from 'react';
import {
  View, Text, StyleSheet, SafeAreaView, TouchableOpacity,
  TextInput, ScrollView, ActivityIndicator, KeyboardAvoidingView, Platform, Alert,
} from 'react-native';
import { router } from 'expo-router';
import { Colors } from '../../constants/Colors';
import { Typography, Spacing, BorderRadius } from '../../constants/Typography';
import { useAuthStore } from '../../stores/auth';

type Mode = 'welcome' | 'disclosure' | 'login' | 'register';

export default function WelcomeScreen() {
  const [mode, setMode] = useState<Mode>('welcome');
  const [email, setEmail] = useState('');
  const [password, setPassword] = useState('');
  const [familyName, setFamilyName] = useState('');
  const [formError, setFormError] = useState('');

  const { login, register, isLoading, acceptDisclosure } = useAuthStore();

  const handleLogin = async () => {
    setFormError('');
    if (!email || !password) {
      setFormError('Please enter your email and password.');
      return;
    }
    try {
      await login(email, password);
      // Navigation handled by auth layout redirect
    } catch (err: unknown) {
      const message = err instanceof Error ? err.message : 'Login failed.';
      setFormError(message);
    }
  };

  const handleRegister = async () => {
    setFormError('');
    if (!email || !password) {
      setFormError('Please enter your email and password.');
      return;
    }
    if (password.length < 8) {
      setFormError('Password must be at least 8 characters.');
      return;
    }
    try {
      await register(email, password, familyName || undefined);
    } catch (err: unknown) {
      const message = err instanceof Error ? err.message : 'Registration failed.';
      setFormError(message);
    }
  };

  if (mode === 'welcome') {
    return (
      <SafeAreaView style={styles.container}>
        <ScrollView contentContainerStyle={styles.scrollContent}>
          <View style={styles.logoArea}>
            <Text style={styles.appName}>🙏 Maa</Text>
            <Text style={styles.tagline}>Digital Legacy</Text>
          </View>

          <View style={styles.introCard}>
            <Text style={styles.introTitle}>A Private Family Keepsake</Text>
            <Text style={styles.introText}>
              Maa lets you revisit the remembered personality, stories, and wisdom of your
              grandmother — recreated thoughtfully from family-provided memories and recordings.
            </Text>
          </View>

          <View style={styles.disclosureCard}>
            <Text style={styles.disclosureTitle}>⚠️ Important to Know</Text>
            <Text style={styles.disclosureText}>
              This app uses artificial intelligence to reflect your grandmother's known personality
              and communication style. It is <Text style={styles.bold}>not</Text> her, does not
              have her real memories or consciousness, and AI responses should be understood as such.
            </Text>
            <Text style={styles.disclosureText}>
              All responses are generated by AI, based on family-approved materials.
            </Text>
          </View>

          <TouchableOpacity
            style={styles.primaryButton}
            onPress={() => setMode('disclosure')}
          >
            <Text style={styles.primaryButtonText}>I Understand — Continue</Text>
          </TouchableOpacity>
        </ScrollView>
      </SafeAreaView>
    );
  }

  if (mode === 'disclosure') {
    return (
      <SafeAreaView style={styles.container}>
        <ScrollView contentContainerStyle={styles.scrollContent}>
          <Text style={styles.sectionTitle}>Before You Begin</Text>

          <View style={styles.disclosureCard}>
            <Text style={styles.disclosureText}>
              By continuing, you confirm that you understand:
            </Text>
            {[
              'This AI is not your grandmother. It does not have her real memories, feelings, or awareness.',
              'Responses are generated by AI from family-approved materials.',
              'The AI may not always be accurate and should not be treated as a historical record.',
              'You can delete your conversations and memories at any time.',
              'Family media shared with the app is stored privately and never made public.',
            ].map((point, i) => (
              <View key={i} style={styles.bulletRow}>
                <Text style={styles.bullet}>•</Text>
                <Text style={styles.bulletText}>{point}</Text>
              </View>
            ))}
          </View>

          <TouchableOpacity
            style={styles.primaryButton}
            onPress={() => {
              acceptDisclosure();
              setMode('login');
            }}
          >
            <Text style={styles.primaryButtonText}>I Understand — Sign In or Register</Text>
          </TouchableOpacity>

          <TouchableOpacity onPress={() => setMode('welcome')} style={styles.backButton}>
            <Text style={styles.backButtonText}>← Back</Text>
          </TouchableOpacity>
        </ScrollView>
      </SafeAreaView>
    );
  }

  return (
    <SafeAreaView style={styles.container}>
      <KeyboardAvoidingView
        behavior={Platform.OS === 'ios' ? 'padding' : 'height'}
        style={styles.flex}
      >
        <ScrollView contentContainerStyle={styles.scrollContent}>
          <Text style={styles.appName}>🙏 Maa</Text>

          <View style={styles.tabRow}>
            <TouchableOpacity
              style={[styles.tab, mode === 'login' && styles.tabActive]}
              onPress={() => setMode('login')}
            >
              <Text style={[styles.tabText, mode === 'login' && styles.tabTextActive]}>Sign In</Text>
            </TouchableOpacity>
            <TouchableOpacity
              style={[styles.tab, mode === 'register' && styles.tabActive]}
              onPress={() => setMode('register')}
            >
              <Text style={[styles.tabText, mode === 'register' && styles.tabTextActive]}>Register</Text>
            </TouchableOpacity>
          </View>

          {formError ? (
            <View style={styles.errorCard}>
              <Text style={styles.errorText}>{formError}</Text>
            </View>
          ) : null}

          {mode === 'register' && (
            <View style={styles.inputGroup}>
              <Text style={styles.label}>Your Name (optional)</Text>
              <TextInput
                style={styles.input}
                value={familyName}
                onChangeText={setFamilyName}
                placeholder="e.g. Raj Mehta"
                placeholderTextColor={Colors.textMuted}
                autoCapitalize="words"
              />
            </View>
          )}

          <View style={styles.inputGroup}>
            <Text style={styles.label}>Email Address</Text>
            <TextInput
              style={styles.input}
              value={email}
              onChangeText={setEmail}
              placeholder="you@family.com"
              placeholderTextColor={Colors.textMuted}
              keyboardType="email-address"
              autoCapitalize="none"
              autoComplete="email"
            />
          </View>

          <View style={styles.inputGroup}>
            <Text style={styles.label}>Password</Text>
            <TextInput
              style={styles.input}
              value={password}
              onChangeText={setPassword}
              placeholder={mode === 'register' ? 'At least 8 characters' : '••••••••'}
              placeholderTextColor={Colors.textMuted}
              secureTextEntry
              autoComplete={mode === 'register' ? 'new-password' : 'current-password'}
            />
          </View>

          <TouchableOpacity
            style={[styles.primaryButton, isLoading && styles.buttonDisabled]}
            onPress={mode === 'login' ? handleLogin : handleRegister}
            disabled={isLoading}
          >
            {isLoading ? (
              <ActivityIndicator color={Colors.textOnPrimary} />
            ) : (
              <Text style={styles.primaryButtonText}>
                {mode === 'login' ? 'Sign In' : 'Create Account'}
              </Text>
            )}
          </TouchableOpacity>

          <TouchableOpacity onPress={() => setMode('welcome')} style={styles.backButton}>
            <Text style={styles.backButtonText}>← Back</Text>
          </TouchableOpacity>
        </ScrollView>
      </KeyboardAvoidingView>
    </SafeAreaView>
  );
}

